"""Local PDF and JSON report generation."""
from __future__ import annotations

import json
import logging
import os
import re
import tempfile
from datetime import datetime
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from modules.firmware import redact_sensitive_text


_REDACTED = "[REDACTED]"


def _is_sensitive_key(key: str) -> bool:
    normalized = re.sub(r"[^a-z0-9]", "", key.lower())
    if normalized == "match":
        return True
    if normalized in {"credentialfinding", "credentialfindings"}:
        return False
    sensitive_parts = (
        "password",
        "passwd",
        "pwd",
        "secret",
        "token",
        "apikey",
        "privatekey",
        "authorization",
    )
    return any(part in normalized for part in sensitive_parts) or (
        "credential" in normalized
        and not normalized.endswith(("finding", "findings", "count", "summary"))
    )


def sanitize_report_data(value):
    """Return a report-safe copy without common secret fields or patterns."""
    if isinstance(value, dict):
        sanitized = {}
        for key, item in value.items():
            if _is_sensitive_key(str(key)):
                sanitized[key] = _REDACTED if item not in (None, "") else item
            else:
                sanitized[key] = sanitize_report_data(item)
        return sanitized
    if isinstance(value, (list, tuple)):
        return [sanitize_report_data(item) for item in value]
    if isinstance(value, str):
        return redact_sensitive_text(value)
    return value


def _create_report_directory(report_path: str | os.PathLike) -> Path:
    directory = Path(report_path)
    directory.mkdir(parents=True, exist_ok=True)
    return directory


def _report_target(directory: Path, extension: str) -> Path:
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    return directory / f"iothunter_report_{timestamp}.{extension}"


def _create_temporary_report(directory: Path) -> Path:
    with tempfile.NamedTemporaryFile(
        prefix=".iothunter-report-",
        suffix=".tmp",
        dir=directory,
        delete=False,
    ) as temporary:
        return Path(temporary.name)


def _watermark_canvas(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica-Bold", 40)
    canvas.setFillColor(colors.Color(0.85, 0.85, 0.85))
    canvas.translate(A4[0] / 2, A4[1] / 2)
    canvas.rotate(45)
    canvas.drawCentredString(0, 0, "MR CYBER - IOT HUNTER")
    canvas.restoreState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)
    canvas.drawString(
        2 * cm, 1 * cm, "Generated by IoT Hunter | Built by MR CYBER (Harsh Saini)"
    )


def generate_json_report(data, report_path):
    directory = _create_report_directory(report_path)
    path = _report_target(directory, "json")
    temporary_path = _create_temporary_report(directory)
    try:
        with temporary_path.open("w", encoding="utf-8") as report_file:
            json.dump(sanitize_report_data(data), report_file, indent=2, default=str)
        os.replace(temporary_path, path)
    except Exception:
        temporary_path.unlink(missing_ok=True)
        raise
    return str(path)


def generate_pdf_report(data, report_path):
    safe_data = sanitize_report_data(data)
    directory = _create_report_directory(report_path)
    path = _report_target(directory, "pdf")
    temporary_path = _create_temporary_report(directory)
    try:
        doc = SimpleDocTemplate(str(temporary_path), pagesize=A4)
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "TitleC", parent=styles["Title"], textColor=colors.HexColor("#111111")
        )
        story = [
            Paragraph("IoT Hunter Security Report", title_style),
            Paragraph("Built by MR CYBER (Harsh Saini)", styles["Normal"]),
            Paragraph(
                f"Generated: {escape(datetime.now().isoformat())}", styles["Normal"]
            ),
            Spacer(1, 0.5 * cm),
            Paragraph("Executive Summary", styles["Heading2"]),
        ]

        discovery = safe_data.get("discovery", {}) or {}
        devices = discovery.get("devices", []) or []
        cred_hits = safe_data.get("credential_findings", []) or []
        proto_hits = safe_data.get("protocol_findings", []) or []
        anomalies = safe_data.get("anomaly_findings", []) or []
        summary = (
            f"Scanned subnet {escape(str(discovery.get('subnet', 'N/A')))}. "
            f"Discovered {len(devices)} device(s). "
            f"{len(cred_hits)} device(s) with default credentials, "
            f"{len(proto_hits)} insecure protocol instance(s), "
            f"{len(anomalies)} traffic anomaly alert(s)."
        )
        story.append(Paragraph(summary, styles["Normal"]))
        story.append(Spacer(1, 0.5 * cm))

        inventory = safe_data.get("inventory_history", {}) or {}
        if inventory:
            story.append(Paragraph("Inventory Change Summary", styles["Heading2"]))
            story.append(
                Paragraph(
                    f"New devices: {escape(str(inventory.get('new_devices', 0)))} · "
                    f"Missing devices: {escape(str(inventory.get('missing_devices', 0)))} · "
                    f"Changed devices: {escape(str(inventory.get('changed_devices', 0)))}",
                    styles["Normal"],
                )
            )
            story.append(Spacer(1, 0.5 * cm))

        if devices:
            story.append(Paragraph("Discovered Devices", styles["Heading2"]))
            table_data = [["IP", "MAC", "Vendor", "Type", "Open Ports"]]
            for device in devices:
                ports = device.get("open_ports", []) or []
                if not isinstance(ports, (list, tuple, set)):
                    ports = [ports]
                table_data.append(
                    [
                        escape(str(device.get("ip", ""))),
                        escape(str(device.get("mac", ""))),
                        escape(str(device.get("vendor", ""))),
                        escape(str(device.get("device_type", "N/A"))),
                        escape(", ".join(map(str, ports))),
                    ]
                )
            table = Table(table_data, hAlign="LEFT")
            table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#222222")),
                        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                        ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ]
                )
            )
            story.append(table)
            story.append(Spacer(1, 0.5 * cm))

        plan = safe_data.get("remediation_plan", []) or []
        if plan:
            story.append(Paragraph("Remediation Plan", styles["Heading2"]))
            for item in plan:
                priority = escape(str(item.get("priority", "medium")).upper())
                finding = escape(str(item.get("finding", "Finding details unavailable")))
                fix = escape(str(item.get("fix", "Review this finding.")))
                story.append(
                    Paragraph(f"<b>[{priority}]</b> {finding}", styles["Normal"])
                )
                story.append(Paragraph(f"Fix: {fix}", styles["Normal"]))
                for command in item.get("commands", []) or []:
                    story.append(
                        Paragraph(
                            f"&nbsp;&nbsp;&bull; <font face='Courier'>"
                            f"{escape(str(command))}</font>",
                            styles["Normal"],
                        )
                    )
                story.append(Spacer(1, 0.2 * cm))

        doc.build(story, onFirstPage=_watermark_canvas, onLaterPages=_watermark_canvas)
        os.replace(temporary_path, path)
    except Exception:
        temporary_path.unlink(missing_ok=True)
        raise
    return str(path)


def generate_reports(data, report_path):
    json_path = generate_json_report(data, report_path)
    try:
        pdf_path = generate_pdf_report(data, report_path)
    except Exception:
        try:
            Path(json_path).unlink(missing_ok=True)
        except OSError:
            logging.exception("Could not remove incomplete JSON report %s", json_path)
        raise
    return json_path, pdf_path
